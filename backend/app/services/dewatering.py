"""The Dewatering Operations section, read from the mine's own daily table.

IT USED TO READ A KPI PIVOT ON MySQL. `mines_dewatering_daily_data` held one
row per KPI per day -- twelve rows to describe one morning -- so every figure
on this screen came out of a `MAX(CASE WHEN kpi_id = 33 ...)`, the derived
figures were stored alongside their own inputs and had already drifted from
them, and a day could exist with some of its KPIs and not others. That table
is no longer written to; `minehub.dewatering_daily_data` is, by the Enter
Daily Dewatering Data form, and it holds ONE ROW PER DAY with the six derived
figures GENERATED by the database.

So this module is now a projection rather than a reconstruction: every column
it needs is a column, the derived figures cannot disagree with their inputs,
and the kpi_id constants are gone. The response shape is unchanged, which is
why the screen needed no edit.

ONE BEHAVIOUR DID CHANGE, DELIBERATELY. The previous day's closing stock --
the one the Net Stock Change card compares against -- used to be looked up
inside the filtered range, so on the 1st of a month it was always absent and
the card always blank. The new table makes the real answer a single query, so
it asks for the nearest stored day BEFORE the one on screen, whether or not
that day falls in the range.
"""
from __future__ import annotations

from datetime import date, timedelta
from typing import Optional

from sqlalchemy import text
from sqlalchemy.orm import Session

from ..schemas.dewatering import (
    DewateringSummaryResponse,
    DewateringTodayKpi,
    DewateringMtdKpi,
    DewateringDayRow,
)

TABLE = "minehub.dewatering_daily_data"


def _f(val) -> Optional[float]:
    return float(val) if val is not None else None


def _date_spine(from_date: date, to_date: date) -> list:
    n = (to_date - from_date).days + 1
    return [from_date + timedelta(days=i) for i in range(n)]


def get_summary(db: Session, from_date: date,
                to_date: date) -> DewateringSummaryResponse:
    # ── 1. The days themselves ────────────────────────────────────────────
    # One row per day, so no pivot and no grouping. The column names are
    # mapped to the screen's names here, in one place, rather than the screen
    # learning the table's.
    raw_rows = db.execute(text(f"""
        SELECT data_date                                  AS date,
               opening_stock_m3                           AS open_stock,
               rain_water_m3                              AS rain_added,
               seepage_m3                                 AS seepage,
               plan_pump_hr                               AS pump_plan_hr,
               actual_pump_hr                             AS pump_act_hr,
               plan_disposal_m3                           AS disposal_plan,
               actual_disposal_m3                         AS disposal_act,
               variance_m3                                AS variance,
               closing_stock_m3                           AS closing_stock,
               -- A reason typed as spaces is not a reason.
               NULLIF(TRIM(dewatering_reason), '')        AS variance_reason,
               pump_capacity_m3_hr                        AS pump_capacity,
               eddy_day_min                               AS eddy_day
        FROM   {TABLE}
        WHERE  data_date BETWEEN :from_date AND :to_date
        ORDER  BY data_date
    """), {"from_date": from_date, "to_date": to_date}).fetchall()

    data_rows = [
        DewateringDayRow(
            date=str(r.date),
            open_stock=_f(r.open_stock),
            rain_added=_f(r.rain_added),
            seepage=_f(r.seepage),
            pump_plan_hr=_f(r.pump_plan_hr),
            pump_act_hr=_f(r.pump_act_hr),
            disposal_plan=_f(r.disposal_plan),
            disposal_act=_f(r.disposal_act),
            variance=_f(r.variance),
            closing_stock=_f(r.closing_stock),
            variance_reason=r.variance_reason,
        )
        for r in raw_rows
    ]
    # Pump capacity and EDDY minutes are not columns of the day table on
    # screen, but they are columns of the day in the database -- so they are
    # carried here per day rather than re-queried for one date, which is what
    # the old pivot had to do.
    extras = {str(r.date): {"pump_capacity": _f(r.pump_capacity),
                            "eddy_day": _f(r.eddy_day)} for r in raw_rows}

    # The full spine, so a day with no entry still gets a line in the table.
    data_by_date = {r.date: r for r in data_rows}
    rows = [
        data_by_date.get(str(dt), DewateringDayRow(
            date=str(dt),
            open_stock=None, rain_added=None, seepage=None, pump_plan_hr=None,
            pump_act_hr=None, disposal_plan=None, disposal_act=None,
            variance=None, closing_stock=None, variance_reason=None,
        ))
        for dt in _date_spine(from_date, to_date)
    ]

    # ── 2. The day cards: the latest day that CARRIES figures ─────────────
    #
    # Not simply the last row. A row can exist holding nothing but a rainfall
    # reading -- the mine does file one on its own, the morning after -- and
    # none of the five day cards read rainfall, so such a day would blank all
    # of them and Net Stock Change with them. That is exactly what happened on
    # 5 October 2026 under the old table, and the new one can hold the same
    # shape of day, so the guard stays.
    def _has_data(r: DewateringDayRow) -> bool:
        return any(v is not None for v in (
            r.open_stock, r.rain_added, r.seepage, r.pump_plan_hr,
            r.pump_act_hr, r.disposal_plan, r.disposal_act, r.variance,
            r.closing_stock,
        ))

    entered_rows = [r for r in data_rows if _has_data(r)]
    latest_row = entered_rows[-1] if entered_rows else None

    entered_dates = {r.date for r in entered_rows}
    missing_dates = [str(dt) for dt in _date_spine(from_date, to_date)
                     if str(dt) not in entered_dates]

    # The closing stock the day on screen opened from. THE NEAREST EARLIER
    # STORED DAY, not calendar day-1 and not only within the range: the mine
    # misses days, and on the 1st of a month the day before is outside the
    # filter entirely -- which is why this card used to be blank every 1st.
    prev_close: Optional[float] = None
    if latest_row:
        prev_close = _f(db.execute(text(f"""
            SELECT closing_stock_m3 FROM {TABLE}
            WHERE  data_date < :d AND closing_stock_m3 IS NOT NULL
            ORDER  BY data_date DESC LIMIT 1
        """), {"d": latest_row.date}).scalar())

    if latest_row:
        d_actual = latest_row.disposal_act
        d_plan = latest_row.disposal_plan
        d_var = latest_row.variance
        d_pct = (round(d_actual / d_plan * 100, 2)
                 if (d_plan and d_actual is not None) else None)
        p_actual = latest_row.pump_act_hr
        p_plan = latest_row.pump_plan_hr
        p_pct = (round(p_actual / p_plan * 100, 2)
                 if (p_plan and p_actual is not None) else None)
        close = latest_row.closing_stock
        delta = (round(close - prev_close, 1)
                 if (close is not None and prev_close is not None) else None)
        lat_date = latest_row.date
        day_num = int(lat_date.split("-")[2])
        extra = extras.get(lat_date, {})
    else:
        d_actual = d_plan = d_var = d_pct = None
        p_actual = p_plan = p_pct = None
        close = delta = None
        lat_date = str(to_date)
        day_num = to_date.day
        extra = {}

    today = DewateringTodayKpi(
        latest_date=lat_date,
        day_num=day_num,
        disposal_actual=d_actual,
        disposal_plan=d_plan,
        disposal_variance=d_var,
        disposal_pct=d_pct,
        pump_actual_hr=p_actual,
        pump_plan_hr=p_plan,
        pump_pct=p_pct,
        closing_stock=close,
        prev_closing_stock=prev_close,
        stock_delta=delta,
        pump_capacity=extra.get("pump_capacity"),
        eddy_pump_mins=extra.get("eddy_day"),
    )

    # ── 3. The period totals ──────────────────────────────────────────────
    m = db.execute(text(f"""
        SELECT SUM(plan_disposal_m3)   AS mtd_disp_plan,
               SUM(actual_disposal_m3) AS mtd_disp_act,
               SUM(plan_pump_hr)       AS mtd_pump_plan,
               SUM(actual_pump_hr)     AS mtd_pump_act,
               SUM(rain_water_m3)      AS mtd_rain
        FROM   {TABLE}
        WHERE  data_date BETWEEN :from_date AND :to_date
    """), {"from_date": from_date, "to_date": to_date}).fetchone()

    mtd_d_plan = _f(m.mtd_disp_plan) or 0.0
    mtd_d_act = _f(m.mtd_disp_act) or 0.0
    mtd_p_plan = _f(m.mtd_pump_plan) or 0.0
    mtd_p_act = _f(m.mtd_pump_act) or 0.0
    mtd_rain = _f(m.mtd_rain) or 0.0

    # First and last ENTERED day, so a trailing rain-only day cannot null the
    # closing stock and blank Net Stock Change.
    d1_open = entered_rows[0].open_stock if entered_rows else None
    d_last_c = entered_rows[-1].closing_stock if entered_rows else None
    net_chg = (round(d_last_c - d1_open, 1)
               if (d_last_c is not None and d1_open is not None) else None)

    mtd = DewateringMtdKpi(
        days=len(entered_rows),
        mtd_disposal_actual=mtd_d_act,
        mtd_disposal_plan=mtd_d_plan,
        mtd_disposal_pct=(round(mtd_d_act / mtd_d_plan * 100, 1)
                          if mtd_d_plan else None),
        mtd_pump_actual_hr=mtd_p_act,
        mtd_pump_plan_hr=mtd_p_plan,
        mtd_pump_pct=(round(mtd_p_act / mtd_p_plan * 100, 1)
                      if mtd_p_plan else None),
        mtd_rain_inflow=mtd_rain,
        net_stock_change=net_chg,
        d1_open_stock=d1_open,
        d_last_close_stock=d_last_c,
    )

    return DewateringSummaryResponse(
        from_date=str(from_date),
        to_date=str(to_date),
        today=today,
        mtd=mtd,
        rows=rows,
        missing_dates=missing_dates,
    )
