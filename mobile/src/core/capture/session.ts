/** Everything standing between this draft and the outbox. */
export async function review(
  store: Store, uuid: string, items: ChecklistItem[], asset: CachedAsset,
): Promise<{ verdict: SessionVerdict; blockers: string[] }> {
  const session = await byUuid(store, uuid);
  if (!session) throw new Error(`no such draft: ${uuid}`);

  const rows = await responses(store, uuid);
  const photoCounts = await store.getAllAsync<{ item_id: number | null; n: number }>(
    `SELECT item_id, COUNT(*) AS n FROM photo WHERE session_uuid = ? GROUP BY item_id`,
    [uuid],
  );
  const photosFor = new Map(photoCounts.map((p) => [p.item_id, p.n]));

  const answers = new Map<number, RawResponse>();
  for (const r of rows) {
    answers.set(r.item_id, {
      itemId: r.item_id,
      answer: r.answer,
      numericValue: r.numeric_value,
      remark: r.remark,
      photoCount: photosFor.get(r.item_id) ?? 0,
    });
  }

  const verdict = evaluateSession({
    items, answers,
    sessionType: session.session_type,
    meterReading: session.meter_reading,
    lastMeterReading: asset.last_meter_reading,
    remarks: session.remarks,
  });

  // Separate from the verdict's own problems: these are things the FLOW
  // requires, not things the checklist does.
  const blockers: string[] = [];
  if (!session.operator_id) blockers.push('Nobody has been identified as the operator');
  const q = counterpartQuestion(session.session_type);
  if (q && session.counterpart_operator_id == null && !session.counterpart_absent) {
    blockers.push(q.missing);
  }
  if (!session.template_id) {
    blockers.push(`No checklist is published for ${asset.asset_type_name} on this tablet`);
  }
  if (session.meter_reading == null) blockers.push('The meter reading has not been entered');
  const fuel = fuelProblem(session.fuel_level);
  if (fuel) blockers.push(fuel);

  return { verdict, blockers };
}

/**
 * The operator attests. The session leaves `draft` and joins the outbox.
 *
 * A BLOCKED handover is still confirmed and still queued. That is the point:
 * the fact that a machine failed its brake check is exactly the record the
 * mine needs, and a flow that only sent passes would make every blocked
 * machine invisible.
 */
export async function confirm(args: {
  store: Store; uuid: string; items: ChecklistItem[]; asset: CachedAsset;
  confirmedBy: string; now?: Date;
}): Promise<{ queued: boolean; status: string; problems: string[]; verdict: SessionVerdict }> {
  const { store, uuid, items, asset, confirmedBy } = args;
  const now = args.now ?? new Date();

  const { verdict, blockers } = await review(store, uuid, items, asset);
  const problems = [...blockers, ...verdict.problems,
                    ...verdict.unanswered.map((i) => `${i.label}: not answered`)];
  if (problems.length > 0) {
    return { queued: false, status: 'DRAFT', problems, verdict };
  }

  const status = verdict.isBlocked ? 'BLOCKED' : 'SUBMITTED';
  await store.runAsync(
    // Nobody else named as holding the tablet means the operator did. Written
    // now rather than when the operator was picked, so it is whoever the
    // operator finally IS. SQLite evaluates every SET against the row as it
    // stood, so the CASE sees the recorder before this statement.
    `UPDATE session SET status = ?, blocked_reason = ?, confirmed_by = ?,
                        confirmed_at = ?, sync_state = 'queued',
                        recorded_by_emp_id = CASE WHEN recorded_by_operator_id IS NULL
                                                  THEN operator_emp_id
                                                  ELSE recorded_by_emp_id END,
                        recorded_by_operator_id = COALESCE(recorded_by_operator_id, operator_id)
      WHERE client_uuid = ? AND sync_state = 'draft'`,
    [status, verdict.blockedReason, confirmedBy, now.toISOString(), uuid],
  );

  return { queued: true, status, problems: [], verdict };
}

/** Drafts this tablet has not finished, so the home screen can offer to resume. */
export async function openDrafts(store: Store): Promise<(SessionRow & { fleet_code: string })[]> {
  return store.getAllAsync<SessionRow & { fleet_code: string }>(
    `SELECT s.*, a.fleet_code FROM session s
       LEFT JOIN cached_asset a ON a.asset_id = s.asset_id
      WHERE s.sync_state = 'draft'
      ORDER BY s.captured_at DESC`,
  );
}

/** What is waiting to reach the server, for the sync banner. */
export async function outboxDepth(store: Store): Promise<{
  queued: number; sending: number; rejected: number; conflict: number; photos: number;
}> {
  const s = await store.getAllAsync<{ sync_state: SyncState; n: number }>(
    `SELECT sync_state, COUNT(*) AS n FROM session GROUP BY sync_state`,
  );
  const p = await store.getFirstAsync<{ n: number }>(
    `SELECT COUNT(*) AS n FROM photo WHERE sync_state IN ('queued','sending')`,
  );
  const at = (k: SyncState) => s.find((r) => r.sync_state === k)?.n ?? 0;
  return {
    queued: at('queued'), sending: at('sending'),
    rejected: at('rejected'), conflict: at('conflict'),
    photos: p?.n ?? 0,
  };
}

/**
 * The payload the server's POST /api/hoto/sessions expects.
 *
 * Built from the stored record, not from screen state, so what is sent is what
 * was signed. `client_uuid` is what makes the retry in phase 11 safe.
 */
export async function payloadFor(store: Store, uuid: string): Promise<Record<string, unknown>> {
  const s = await byUuid(store, uuid);
  if (!s) throw new Error(`no such session: ${uuid}`);
  const rows = await responses(store, uuid);
  const photos = await store.getAllAsync<{ item_id: number | null; n: number }>(
    `SELECT item_id, COUNT(*) AS n FROM photo WHERE session_uuid = ? GROUP BY item_id`, [uuid],
  );
  const photosFor = new Map(photos.map((p) => [p.item_id, p.n]));

  return {
    client_uuid: s.client_uuid,
    asset_id: s.asset_id,
    shift_instance_id: s.shift_instance_id,
    session_type: s.session_type,
    sequence_no: s.sequence_no,
    operator_id: s.operator_id,
    operator_emp_id: s.operator_emp_id,
    template_id: s.template_id,
    template_version: s.template_version,
    meter_reading: s.meter_reading,
    meter_uom: s.meter_uom,
    fuel_level: s.fuel_level,
    location_id: s.location_id,
    status: s.status,
    blocked_reason: s.blocked_reason,
    captured_at: s.captured_at,
    // LOCAL DAY, NOT THE UTC SLICE. captured_at is written with
    // toISOString(), so slicing the first ten characters gave the UTC date:
    // in IST every capture between 00:00 and 05:29 local reported the
    // PREVIOUS day -- precisely the night shift. The server recomputes the
    // stored production day correctly, so only template resolution used
    // this; but a checklist published overnight would have been resolved
    // against the wrong day for the shift most likely to be working.
    production_day: localDay(s.captured_at),
    captured_offline: s.captured_offline === 1,
    // So the office can tell a one-tap record from a walk-round.
    bulk_answered: (s as any).bulk_answered === 1,
    captured_lat: s.captured_lat,
    captured_lon: s.captured_lon,
    gps_accuracy_m: s.gps_accuracy_m,
    gps_status: s.gps_status,
    master_cache_age_hours: s.master_cache_age_hours,
    remarks: s.remarks,
    // Everyone in it (migration 115). A mid-shift check has no other side,
    // and the server refuses one that claims to.
    counterpart_operator_id: s.session_type === 'MID_SHIFT' ? null : s.counterpart_operator_id,
    counterpart_emp_id: s.session_type === 'MID_SHIFT' ? null : s.counterpart_emp_id,
    counterpart_absent: s.session_type !== 'MID_SHIFT' && s.counterpart_absent === 1,
    recorded_by_operator_id: s.recorded_by_operator_id,
    recorded_by_emp_id: s.recorded_by_emp_id,
    responses: rows.map((r) => ({
      item_id: r.item_id,
      answer: r.answer,
      numeric_value: r.numeric_value,
      remark: r.remark,
      photo_count: photosFor.get(r.item_id) ?? 0,
    })),
  };
}

/**
 * Remove drafts that can never be finished: no checklist was found for the
 * machine, and nothing has been answered or photographed.
 *
 * Until 16 Nov a draft was written before the checklist was looked up, so
 * picking a machine with no checklist left an "Unfinished -- 0 of 0 checks"
 * card on the home screen for ever, one more each time. Nothing can be done
 * with one -- there are no questions to answer -- and it holds nothing, so
 * removing it loses nothing. A draft with ANY answer or photo is never
 * touched here, checklist or not.
 */
export async function removeEmptyDraftsWithoutChecklist(store: Store): Promise<number> {
  const r = await store.runAsync(
    `DELETE FROM session
      WHERE sync_state = 'draft' AND template_id IS NULL
        AND NOT EXISTS (SELECT 1 FROM response x WHERE x.session_uuid = session.client_uuid)
        AND NOT EXISTS (SELECT 1 FROM photo p WHERE p.session_uuid = session.client_uuid)`);
  return r.changes;
}
