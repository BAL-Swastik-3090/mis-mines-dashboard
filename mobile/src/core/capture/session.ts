export interface SessionRow {
  client_uuid: string;
  asset_id: number;
  shift_instance_id: number | null;
  session_type: SessionType;
  sequence_no: number;
  operator_id: number | null;
  operator_emp_id: string | null;
  identified_by: IdentificationMethod | null;
  counterpart_uuid: string | null;
  template_id: number | null;
  template_version: number | null;
  meter_reading: number | null;
  meter_uom: string | null;
  fuel_level: number | null;
  location_id: number | null;
  status: string;
  blocked_reason: string | null;
  confirmed_by: string | null;
  confirmed_at: string | null;
  sync_state: SyncState;
  captured_at: string;
  captured_offline: number;
  captured_lat: number | null;
  captured_lon: number | null;
  gps_accuracy_m: number | null;
  gps_status: GpsStatus | null;
  master_cache_age_hours: number | null;
  remarks: string | null;
  // ── everyone in it (schema v8) ──
  /** Who handed over (a takeover) or who took over (a handover). */
  counterpart_operator_id: number | null;
  counterpart_emp_id: string | null;
  /** 1 when the operator said nobody was there -- first start, parked machine. */
  counterpart_absent: number;
  /** Who held the tablet. Set to the operator at confirm when nobody else was named. */
  recorded_by_operator_id: number | null;
  recorded_by_emp_id: string | null;
}

export interface ResponseRow {
  local_id: number;
  session_uuid: string;
  item_id: number;
  item_label: string;
  response_type: string;
  answer: Answer | null;
  numeric_value: number | null;
  in_range: number | null;
  severity: string | null;
  remark: string | null;
}

/** Things worth telling the operator that are not reasons to stop him. */
export interface Advisory {
  kind: 'COMPETENCY' | 'COMPETENCY_EXPIRED' | 'STALE_MASTERS' | 'OPEN_DEFECTS'
      | 'MACHINE_HELD' | 'NO_GPS';
  message: string;
}

export interface StartArgs {
  store: Store;
  asset: CachedAsset;
  sessionType: SessionType;
  /** Generated by the caller (expo-crypto randomUUID) so this stays testable. */
  clientUuid: string;
  shiftInstanceId?: number | null;
  now?: Date;
}

/**
 * Open a draft for this machine.
 *
 * Returns the existing draft if one is already open for the same machine,
 * shift and type. A tablet that crashed mid-walk-round must resume rather than
 * start again — and starting again would also burn a sequence number, making
 * the record look like two handovers happened.
 */
/**
 * `hoto_session.client_uuid` is a Postgres `uuid` column, so anything that is
 * not one is refused by the database -- and refused at the GATE, on sync, hours
 * after the operator has walked away from the machine. Checking it here turns
 * that into an error at the cab, where somebody can still do something about
 * it. Found by the contract test, which is exactly what it is for.
 */
const UUID_RE =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export async function startDraft(args: StartArgs): Promise<{ session: SessionRow; resumed: boolean }> {
  const { store, asset, sessionType, clientUuid } = args;
  if (!UUID_RE.test(clientUuid)) {
    throw new Error(
      `client_uuid must be a UUID, got ${JSON.stringify(clientUuid)} — ` +
      `the server stores it in a uuid column and would refuse this on sync`,
    );
  }
  const now = args.now ?? new Date();
  const shiftInstanceId = args.shiftInstanceId ?? null;

  const open = await store.getFirstAsync<SessionRow>(
    `SELECT * FROM session
      WHERE asset_id = ? AND session_type = ? AND sync_state = 'draft'
        AND COALESCE(shift_instance_id, -1) = COALESCE(?, -1)
      ORDER BY captured_at DESC LIMIT 1`,
    [asset.asset_id, sessionType, shiftInstanceId],
  );
  if (open) return { session: open, resumed: true };

  // Sequence per machine, shift and type, the same key the server uses for its
  // UNIQUE constraint. Counted locally because there is no network; the server
  // recomputes it on receipt and its answer wins.
  const seqRow = await store.getFirstAsync<{ n: number }>(
    `SELECT COALESCE(MAX(sequence_no), 0) + 1 AS n FROM session
      WHERE asset_id = ? AND session_type = ?
        AND COALESCE(shift_instance_id, -1) = COALESCE(?, -1)`,
    [asset.asset_id, sessionType, shiftInstanceId],
  );

  const template = await resolveTemplate(store, asset.asset_type_id,
                                         now.toISOString().slice(0, 10));
  const ageHours = await cacheAgeHours(store, now);

  await store.runAsync(
    `INSERT INTO session
       (client_uuid, asset_id, shift_instance_id, session_type, sequence_no,
        template_id, template_version, meter_uom, location_id,
        status, sync_state, captured_at, captured_offline,
        master_cache_age_hours)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 'DRAFT', 'draft', ?, 1, ?)`,
    [clientUuid, asset.asset_id, shiftInstanceId, sessionType, seqRow?.n ?? 1,
     template?.template_id ?? null, template?.version ?? null,
     asset.meter_uom, asset.home_location_id,
     now.toISOString(), ageHours],
  );

  const session = await byUuid(store, clientUuid);
  if (!session) throw new Error('draft was not written');
  return { session, resumed: false };
}

export async function byUuid(store: Store, uuid: string): Promise<SessionRow | null> {
  return store.getFirstAsync<SessionRow>(
    `SELECT * FROM session WHERE client_uuid = ?`, [uuid],
  );
}

/**
 * Attach the operator who is attesting to this handover.
 *
 * ONE OPERATOR PER SESSION, and never inherited on a shared tablet: the person
 * who signs is the person at the machine, and a device that remembered the
 * last operator would quietly put the previous shift's name on this one.
 * `mayInheritIdentity` in enums.ts is what decides whether that is allowed, and
 * it is only ever true for a personal device.
 */
export async function identify(
  store: Store, uuid: string, op: CachedOperator,
  method: IdentificationMethod, asset: CachedAsset, now = new Date(),
): Promise<Advisory[]> {
  const before = await byUuid(store, uuid);
  await store.runAsync(
    `UPDATE session SET operator_id = ?, operator_emp_id = ?, identified_by = ?
      WHERE client_uuid = ?`,
    [op.operator_id, op.emp_id, method, uuid],
  );

  // ── A PHOTOGRAPH OF SOMEBODY ELSE ─────────────────────────────────────────
  // The operator photo is a record of WHO was standing at the machine. If the
  // operator is changed after it was taken, it is a photograph of the wrong
  // person attached to this one's name -- worse than no photo, because it
  // looks like evidence. A draft's photos are held back from sync until the
  // handover is confirmed (engine.ts), so this one has not left the tablet
  // and removing it loses nothing that was ever filed.
  if (before?.operator_id != null && before.operator_id !== op.operator_id) {
    await store.runAsync(
      `DELETE FROM photo WHERE session_uuid = ? AND kind = 'OPERATOR'
         AND sync_state IN ('queued', 'rejected')`,
      [uuid],
    );
  }
  return advisoriesFor(op, asset, now);
}

/**
 * The other side of the handover: who handed it over, or who it is handed to.
 *
 * `op = null, absent = true` is an ANSWER -- "nobody; it was parked" -- and is
 * recorded as one. `op = null, absent = false` clears the question so it is
 * asked again. The two must never be confused: a register that showed an
 * unasked question as "nobody was there" would be inventing a fact.
 */
export async function setCounterpart(
  store: Store, uuid: string, op: CachedOperator | null, absent = false,
): Promise<void> {
  if (op && absent) throw new Error('the other side is either named or absent, not both');
  await store.runAsync(
    `UPDATE session SET counterpart_operator_id = ?, counterpart_emp_id = ?,
                        counterpart_absent = ?
      WHERE client_uuid = ?`,
    [op?.operator_id ?? null, op?.emp_id ?? null, absent ? 1 : 0, uuid],
  );
}

/**
 * Who is holding the tablet, when it is not the operator.
 *
 * `null` means the operator is filling it in themself, which is resolved to
 * their own name at confirm -- not stored now, because the operator may still
 * be changed and the record must name whoever it ends up being.
 */
export async function setRecorder(
  store: Store, uuid: string, op: CachedOperator | null,
): Promise<void> {
  await store.runAsync(
    `UPDATE session SET recorded_by_operator_id = ?, recorded_by_emp_id = ?
      WHERE client_uuid = ?`,
    [op?.operator_id ?? null, op?.emp_id ?? null, uuid],
  );
}

/**
 * Fuel is a percentage. The office's database refuses anything outside 0-100,
 * and a handover it refuses is retried for ever from a tablet that has no way
 * to correct it -- so it is refused here, at the machine, instead.
 */
export function fuelProblem(v: number | null | undefined): string | null {
  if (v == null) return null;
  if (!Number.isFinite(v) || v < 0 || v > 100) return 'Fuel must be between 0 and 100 per cent';
  return null;
}

/** What the other-side question is called for this kind of session, or null. */
export function counterpartQuestion(t: SessionType): {
  label: string; nobody: string; missing: string;
} | null {
  switch (t) {
    case 'START_HANDOVER':
      return { label: 'Handed over by',
               nobody: 'Nobody — the machine was parked',
               missing: 'Say who handed the machine over, or that nobody did' };
    case 'END_HANDOVER':
      return { label: 'Handing over to',
               nobody: 'Nobody — I am parking it',
               missing: 'Say who is taking the machine over, or that nobody is' };
    case 'MID_SHIFT':
      return null;
  }
}

/**
 * What the operator should be told before he starts — none of it blocking.
 *
 * Competency is the one the mine still has to rule on. Until it does, taking a
 * machine outside what you are signed off on is recorded and shown, not
 * refused: see the file header.
 */
export function advisoriesFor(
  op: CachedOperator | null, asset: CachedAsset, now = new Date(),
  cacheAge?: number | null,
): Advisory[] {
  const out: Advisory[] = [];

  if (op) {
    let competent: number[] = [];
    try {
      const parsed: unknown = JSON.parse(op.competent_type_ids || '[]');
      if (Array.isArray(parsed)) competent = parsed.filter((n): n is number => typeof n === 'number');
    } catch {
      // A malformed cache must not stop a handover. Treated as "no competency
      // recorded", which produces the advisory below rather than silence.
      competent = [];
    }

    if (!competent.includes(asset.asset_type_id)) {
      out.push({
        kind: 'COMPETENCY',
        message: `${op.name} is not signed off on ${asset.asset_type_name}. ` +
                 `The handover will be recorded and raised for a supervisor.`,
      });
    } else if (op.competency_valid_to && Date.parse(op.competency_valid_to) < now.getTime()) {
      out.push({
        kind: 'COMPETENCY_EXPIRED',
        message: `${op.name}'s competency for ${asset.asset_type_name} expired on ` +
                 `${op.competency_valid_to.slice(0, 10)}.`,
      });
    }
  }

  if (asset.has_critical_defect === 1) {
    out.push({
      kind: 'MACHINE_HELD',
      message: `${asset.fleet_code} has a critical defect against it and should not ` +
               `be worked until it has been verified repaired.`,
    });
  } else if (asset.open_defect_count > 0) {
    out.push({
      kind: 'OPEN_DEFECTS',
      message: `${asset.fleet_code} has ${asset.open_defect_count} open ` +
               `defect${asset.open_defect_count === 1 ? '' : 's'} against it.`,
    });
  }

  if (cacheAge != null && cacheAge >= 24) {
    out.push({
      kind: 'STALE_MASTERS',
      message: `This tablet last synced ${Math.floor(cacheAge / 24)} day(s) ago. ` +
               `Machine and operator details may have changed.`,
    });
  }

  return out;
}

/**
 * Record one answer, evaluated as it is given.
 *
 * The verdict is resolved HERE and stored, not computed when the record is
 * read. A limit the admin panel changes next month must not retrospectively
 * turn a pass into a failure on a record somebody signed.
 */
export async function answer(
  store: Store, uuid: string, item: ChecklistItem, raw: RawResponse,
): Promise<void> {
  const ev = evaluateOne(item, raw);
  await store.runAsync(
    `INSERT INTO response
       (session_uuid, item_id, item_label, response_type, answer, numeric_value,
        in_range, severity, remark)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
     ON CONFLICT (session_uuid, item_id) DO UPDATE SET
       answer = excluded.answer,
       numeric_value = excluded.numeric_value,
       in_range = excluded.in_range,
       severity = excluded.severity,
       remark = excluded.remark`,
    [uuid, item.itemId, item.label, item.responseType,
     raw.answer ?? null, raw.numericValue ?? null,
     ev.inRange == null ? null : (ev.inRange ? 1 : 0),
     ev.severity, raw.remark ?? null],
  );
}

export async function responses(store: Store, uuid: string): Promise<ResponseRow[]> {
  return store.getAllAsync<ResponseRow>(
    `SELECT * FROM response WHERE session_uuid = ? ORDER BY item_id`, [uuid],
  );
}

