/**
 * One handover, from the moment somebody taps a machine to the moment it joins
 * the outbox.
 *
 * ── THE DRAFT IS WRITTEN BEFORE THE FIRST QUESTION IS ANSWERED ───────────────
 * Not at the end. A tablet in a cab is interrupted by everything — a radio
 * call, a flat battery, somebody needing the machine now — and a flow that
 * only writes on Confirm loses the whole walk-round. The draft row exists from
 * the start and every answer is written as it is given, so an interruption
 * costs the last tap rather than the last twenty minutes.
 *
 * ── CONFIRM IS NOT SEND ──────────────────────────────────────────────────────
 * Confirming moves the session to `queued`, which means the operator has
 * attested to it and the device owns it until the server says otherwise. The
 * screen must never say "submitted" at that moment, because the tablet may not
 * see a network for hours. `sync_state` and `status` stay separate for exactly
 * this reason (see enums.ts).
 *
 * ── WHAT IS RECORDED RATHER THAN REFUSED ─────────────────────────────────────
 * An operator taking a machine he is not signed off on; masters that are days
 * old; GPS denied. None of these stop a handover. The mine has not decided
 * whether competency may be overridden (scope §9, question 3), and a system
 * that refuses a handover that physically happened produces a record that is
 * worse than an awkward one: it produces no record at all, and the machine
 * still goes out.
 */

